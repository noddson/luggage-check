import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const VEHICLES_DIR = 'configs/vehicles';
const INDEX_PATH = path.join(VEHICLES_DIR, 'index.json');
const GENERATED_NOTE = 'Generated by scripts/generate-vehicle-index.mjs. Do not edit by hand.';

async function discoverVehicleFiles(dir = VEHICLES_DIR) {
  const regions = (await readdir(dir, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  const filesByRegion = await Promise.all(regions.map(async (region) => {
    const regionDir = path.join(dir, region);
    const files = (await readdir(regionDir))
      .filter((file) => file.endsWith('.json'))
      .sort()
      .map((file) => `${region}/${file}`);
    return files;
  }));

  return filesByRegion.flat();
}

function renderIndex(files) {
  return `${JSON.stringify({ generatedBy: GENERATED_NOTE, files }, null, 2)}\n`;
}

const checkOnly = process.argv.includes('--check');
const files = await discoverVehicleFiles();
const expected = renderIndex(files);

if (checkOnly) {
  let current;
  try {
    current = await readFile(INDEX_PATH, 'utf8');
  } catch (error) {
    throw new Error(`${INDEX_PATH} is missing; run node scripts/generate-vehicle-index.mjs`, { cause: error });
  }

  if (current !== expected) {
    throw new Error(`${INDEX_PATH} is stale; run node scripts/generate-vehicle-index.mjs`);
  }

  console.log(`${INDEX_PATH} is up to date with ${files.length} vehicle config files.`);
} else {
  await writeFile(INDEX_PATH, expected);
  console.log(`Wrote ${INDEX_PATH} with ${files.length} vehicle config files.`);
}
